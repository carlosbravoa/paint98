_cache = {}


def make_surface(rows, palette=None, scale=1):
    pal = palette or PALETTE
    h = len(rows)
    w = max(len(r) for r in rows)
    surf = cairo.ImageSurface(cairo.FORMAT_ARGB32, w * scale, h * scale)
    cr = cairo.Context(surf)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "." or ch == " ":
                continue
            r, g, b = pal[ch]
            cr.set_source_rgb(r / 255, g / 255, b / 255)
            cr.rectangle(x * scale, y * scale, scale, scale)
            cr.fill()
    surf.flush()
    return surf


def get(name, scale=1):
    key = (name, scale)
    if key not in _cache:
        if name in TOOL_ICONS:
            rows = TOOL_ICONS[name]
        else:
            rows = globals()[name]
        _cache[key] = make_surface(rows, scale=scale)
    return _cache[key]


def paint(cr, name, x, y, alpha=None, disabled=False):
    """Paint a cached pixmap at integer coordinates without smoothing."""
    surf = get(name)
    cr.save()
    if disabled:
        # Classic embossed look: white offset copy, then gray glyph.
        cr.set_source_rgb(1, 1, 1)
        cr.mask_surface(surf, x + 1, y + 1)
        cr.set_source_rgb(0.5, 0.5, 0.5)
        cr.mask_surface(surf, x, y)
    else:
        cr.set_source_surface(surf, x, y)
        cr.get_source().set_filter(cairo.FILTER_NEAREST)
        if alpha is None:
            cr.paint()
        else:
            cr.paint_with_alpha(alpha)
    cr.restore()
